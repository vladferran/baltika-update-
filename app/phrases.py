def pick(category: str, level: int, **fmt) -> str:
    bank = PHRASES.get(category, {})
    pool = bank.get(level) or bank.get(2) or ["Напоминание о смене."]
    return random.choice(pool).format(**fmt)


def seed_rows() -> list[tuple[str, int, str]]:
    return [
        (cat, lvl, text)
        for cat, levels in PHRASES.items()
        for lvl, texts in levels.items()
        for text in texts
    ]
